"""Generate a512x8 gain-adaptive gamma bank; the low-gain256 entries stay exact.
High-gain shadow toe reduces low-level lifting, and is identical above input31.
Run with Python from the project tree. No third-party dependencies.
"""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parents[1]
dest=root/'user_source/hdl_source/gamma_lut.v'
base=[round(255*(x/255)**(1/2.2)) for x in range(256)]
prior=dest.read_text(encoding='utf-8')
old={int(a):int(b) for a,b in re.findall(r"8'd(\d+)\s*:\s*dout\s*=\s*8'd(\d+)",prior)}
if old:assert len(old)==256 and [old[i] for i in range(256)]==base
toe=[g-(((g-min(g,3*x))*(32-x)+16)//32) if x<32 else g for x,g in enumerate(base)]
assert all(0<=v<=255 for v in toe) and all(a<=b for a,b in zip(toe,toe[1:]))
assert toe[0]==0 and toe[32:]==base[32:] and toe[255]==255
lines=['// Generated by tools/generate_quality_gamma.py.','// Low gain: original gamma. High gain: soft shadow toe below linear32.',
 '// Same curve on R/G/B; no grayscale conversion or chroma suppression.',
 'module gamma_rom_gain_512x8(input wire [8:0] addr,output reg [7:0] dout);','    always @* begin','        case(addr)']
for x,v in enumerate(base+toe):lines.append(f"            9'd{x}:dout=8'd{v};")
lines+=['            default:dout=0;','        endcase','    end','endmodule','', '''module gamma_lut #(
    parameter EN_GAMMA=1'b1,
    parameter EN_BLC=1'b1,
    parameter [7:0] BL_LEVEL=8'd16
)(
    input wire clk,rst_n,
    input wire [1:0] I_nr_level,
    input wire I_vsync,
    input wire [23:0] rgb_in,
    output reg [23:0] rgb_out
);
    reg [1:0] nr_meta,nr_sync,nr_prev;
    reg vs_d,toe_mode;
    // Frame-held slow control, only accepted during vertical sync.
    // It adds no pixel pipeline stages and no new clock domain.
    always @(posedge clk or negedge rst_n) begin
        if(!rst_n) begin nr_meta<=0;nr_sync<=0;nr_prev<=0;vs_d<=0;toe_mode<=0;end
        else begin
            nr_meta<=I_nr_level;nr_sync<=nr_meta;nr_prev<=nr_sync;vs_d<=I_vsync;
            if(I_vsync && !vs_d && nr_sync==nr_prev) toe_mode<=(nr_sync==2);
        end
    end
    wire [7:0] r_in=rgb_in[23:16],g_in=rgb_in[15:8],b_in=rgb_in[7:0];
    wire [7:0] r_bl=EN_BLC?((r_in>BL_LEVEL)?r_in-BL_LEVEL:8'd0):r_in;
    wire [7:0] g_bl=EN_BLC?((g_in>BL_LEVEL)?g_in-BL_LEVEL:8'd0):g_in;
    wire [7:0] b_bl=EN_BLC?((b_in>BL_LEVEL)?b_in-BL_LEVEL:8'd0):b_in;
    wire [7:0] r_out,g_out,b_out;
    gamma_rom_gain_512x8 u_rom_r(.addr({toe_mode,r_bl}),.dout(r_out));
    gamma_rom_gain_512x8 u_rom_g(.addr({toe_mode,g_bl}),.dout(g_out));
    gamma_rom_gain_512x8 u_rom_b(.addr({toe_mode,b_bl}),.dout(b_out));
    // Exactly one output register, matching original gamma_lut and AE PIPE_DELAY1.
    always @(posedge clk or negedge rst_n)
        if(!rst_n) rgb_out<=0;
        else rgb_out<=EN_GAMMA?{r_out,g_out,b_out}:{r_bl,g_bl,b_bl};
endmodule''']
dest.write_bytes(('\n'.join(lines)+'\n').replace('\n','\r\n').encode('utf-8'))
print(json.dumps({'gamma_entries':512,'low_bank_identical':True,'toe_dark_examples':{x:[base[x],toe[x]] for x in [1,4,8,16,24,32,128,255]},'pixel_latency':1}))
