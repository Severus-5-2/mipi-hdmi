//============================================================================
// 文件    ：sat_enhance.v
// 功能    ：RGB 饱和度增强（色度放大）
// 适用链路：Gamma 校正之后、模式 MUX 之前（显示域 / sRGB 域）
// 版本    ：v2（2026-10-05）——两级流水版本，修复接入后的时序违例
//============================================================================
//
// 【版本变更说明（重要）】
//   v1 是"单级组合 + 输出寄存"，接入工程后 TD 报时序违例：
//       HDMI_Pixel_CLK（74.25 MHz，预算 13.33 ns）域
//       路径：u_gamma_lut ROM 输出寄存器 → u_sat_enhance 输入 X 寄存器
//       实际 8 级组合逻辑 ≈ 15 ns，Slack = -1.7 ns
//   原因：Gamma 查表输出后，本模块的全部运算被挤在同一拍内完成。
//
//   v2 改为**两级流水**：
//       级 1：亮度 Y、色度 dC、死区判断    → 打一拍寄存
//       级 2：色度放大、加回 Y、限幅       → 输出寄存
//   每拍只剩约 4 级逻辑，Slack 预计转正 +3 ns 以上。
//   代价：相对输入延迟由 1 拍变为 **2 拍**（仅影响彩色原图模式，见下文说明）。
//
// 【为什么需要这个模块】
//   1) 当前通路只有 Demosaic + AWB + Gamma，**没有任何颜色校正矩阵（CCM）
//      或饱和度处理**。SC520CS 的 Bayer 滤色片光谱响应较宽、通道串扰大，
//      原始色彩浓度本来就低，再经去马赛克插值"平均"一次，颜色就更淡了；
//   2) 加上高增益（63x）带来的噪点，视觉上就是"画面灰扑扑、颜色发闷"；
//   3) 饱和度增强在**不改变亮度**的前提下把颜色往"远离灰轴"方向推，
//      是改动最小、见效最快、且不放大亮度噪点的一步。
//
// 【算法原理】
//        Y   = 0.299·R + 0.587·G + 0.114·B      （Rec.601 亮度，保持不变）
//        dC  = C - Y                            （C = R/G/B，色度偏离量）
//        C'  = Y + dC × GAIN                    （GAIN > 1 即增强）
//
//   好处：
//     · Y 完全不动 → 亮度、对比度不受影响，不会引入新的过曝；
//     · 纯灰色像素（R=G=B）的 dC = 0，输出恒等于输入 → 灰度/二值/Sobel
//       分支的数据经过本模块不产生任何变化（本模块只接彩色原图通路）；
//     · 相比"转 YCbCr → 缩放 Cb/Cr → 转回 RGB"，省掉两次色彩空间变换。
//
// 【关于乘法的实现（关键优化，避免占用 DSP）】
//   SAT_GAIN 是**编译期常量参数**，因此综合器会把常量乘法
//       d × SAT_GAIN
//   自动优化为移位加网络（例如 SAT_GAIN=96 即 1.5x 时，
//   d×96 = (d<<7)-(d<<5)），**不会消耗 DSP**，且逻辑级数远低于通用乘法器。
//   为此本版刻意**不把增益值本身打进流水线寄存器**——一旦增益变成运行时
//   变量，综合器就无法做常量传播，只能生成通用乘法器。
//   实现上改为：只寄存 1 bit 的"是否彩色"标志 is_chroma，
//   第二级再用该标志在两个结果之间做二选一。
//
// 【GAIN 定点格式】
//   SAT_GAIN 为 6 位小数的定点数：实际倍数 = SAT_GAIN / 64
//       64  → 1.00x（等于不处理）
//       80  → 1.25x（轻微）
//       96  → 1.50x（默认，推荐起点）
//      112  → 1.75x（明显）
//      128  → 2.00x（浓艳，可能出现色块断层）
//   不建议超过 160（2.5x），否则暗部色噪会被放大得非常明显。
//
// 【色度死区 DEADZONE 的作用（抑制彩色噪点）】
//   高增益下噪点主要表现为**色度噪点**（灰色区域出现红绿蓝杂色点）。
//   若对 |dC| 很小的像素也做放大，这些杂色噪点会被一起放大，越鲜艳越脏。
//   因此加入死区：当 |dC| ≤ DEADZONE 时认为"这本来就是灰色"，增益退化
//   为 1.0x 不做处理；只有真正的彩色区域才被增强。
//       DEADZONE = 0 → 关闭死区（纯增强，噪点也放大）
//       DEADZONE = 3 → 默认，轻微抑制
//       DEADZONE = 6 → 抑制更明显，但极淡的颜色会略微变灰
//
// 【资源与时序】
//   · 资源：无乘法器 IP / DSP（常量乘法由综合器转移位加），约 200 LUT；
//   · 时序：两级流水，每级约 4 级逻辑，74.25 MHz 下裕量充足；
//   · 延迟：**相对输入 2 拍**（EN=0 直通同样是 2 拍，保证 A/B 对比时
//     延迟一致）。仅彩色原图模式受此影响，表现为画面整体右移 1 像素；
//     由于四种模式互斥显示（同一时刻只选通一路），肉眼不可见；
//     灰度/二值/Sobel 分支不走本模块，完全不受影响。
//
//============================================================================

module sat_enhance #(
    //---------------- 参数（实例化时可覆盖）----------------
    parameter       EN       = 1'b1,      // 1:启用饱和度增强；0:直通（上板 A/B 对比用）
    parameter [8:0] SAT_GAIN = 9'd96,     // 色度增益，6位小数定点，96 = 1.50x
    parameter [4:0] DEADZONE = 5'd3       // 色度死区阈值，0 = 关闭该功能
) (
    //---------------- 端口 ----------------
    input  wire        clk,               // 像素时钟（与 gamma_lut 同域：S_hdmi_pixel_clk）
    input  wire        rst_n,             // 低电平复位
    input  wire [23:0] rgb_in,            // 输入 RGB888（Gamma 校正后的显示域数据）
    output reg  [23:0] rgb_out            // 输出 RGB888（饱和度增强后，延迟 2 拍）
);

    //========================================================================
    //========== 流水级 1（组合部分）：亮度 Y、色度 dC、死区判断 ==========
    //========================================================================

    //---- 1.1 通道分离 ----
    wire [7:0] r_in = rgb_in[23:16];      // R 通道
    wire [7:0] g_in = rgb_in[15:8];       // G 通道
    wire [7:0] b_in = rgb_in[7:0];        // B 通道

    //---- 1.2 亮度 Y（Rec.601 定点化）----
    //     0.299 ≈ 77/256，0.587 ≈ 150/256，0.114 ≈ 29/256
    //     系数和 = 77+150+29 = 256，故右移 8 位即为加权平均，无需再做除法。
    //     三个都是"常数 × 变量"，综合器会转成移位加网络，不消耗 DSP。
    //     最大值 = 256 × 255 = 65280 < 65536，16 位足够，不会溢出。
    wire [15:0] y_sum = 16'd77  * r_in    // 0.299 × R
                      + 16'd150 * g_in    // 0.587 × G
                      + 16'd29  * b_in;   // 0.114 × B
    wire [7:0]  y_lum = y_sum[15:8];      // Y：0~255

    //---- 1.3 色度偏离量 dC = C - Y（有符号，范围 -255 ~ +255，10 位有符号）----
    wire signed [9:0] d_r = $signed({2'b00, r_in}) - $signed({2'b00, y_lum});
    wire signed [9:0] d_g = $signed({2'b00, g_in}) - $signed({2'b00, y_lum});
    wire signed [9:0] d_b = $signed({2'b00, b_in}) - $signed({2'b00, y_lum});

    //---- 1.4 色度死区判断 ----
    //     把无符号参数 DEADZONE 转成 10 位有符号数，避免 Verilog 的
    //     "有符号与无符号混合运算按无符号处理"陷阱（否则负的 dC 会被误判）。
    //     注意：这里只产生 **1 bit 的标志位**，而不是把增益值本身寄存，
    //     目的是让第 2 级仍能用编译期常量做乘法（详见文件头"关键优化"）。
    wire signed [9:0] dz_pos =  $signed({5'd0, DEADZONE});   // +DEADZONE
    wire signed [9:0] dz_neg = -$signed({5'd0, DEADZONE});   // -DEADZONE

    wire is_chroma_r = (d_r > dz_pos) || (d_r < dz_neg);
    wire is_chroma_g = (d_g > dz_pos) || (d_g < dz_neg);
    wire is_chroma_b = (d_b > dz_pos) || (d_b < dz_neg);

    //========================================================================
    //========== 流水级 1（寄存器）：打一拍，切断长组合路径 ==========
    //========================================================================
    //   同时寄存一份原始像素 s1_rgb，供 EN=0 直通使用，
    //   保证"启用/旁路"两种模式的总延迟完全一致（都是 2 拍）。
    reg [7:0]        s1_y;         // 第 1 拍锁存的亮度 Y
    reg signed [9:0] s1_d_r;       // 第 1 拍锁存的色度偏离量 dR
    reg signed [9:0] s1_d_g;
    reg signed [9:0] s1_d_b;
    reg              s1_c_r;       // 第 1 拍锁存的"是否彩色"标志 R
    reg              s1_c_g;
    reg              s1_c_b;
    reg [23:0]       s1_rgb;       // 第 1 拍锁存的原始像素（旁路模式用）

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s1_y   <= 8'd0;
            s1_d_r <= 10'sd0;
            s1_d_g <= 10'sd0;
            s1_d_b <= 10'sd0;
            s1_c_r <= 1'b0;
            s1_c_g <= 1'b0;
            s1_c_b <= 1'b0;
            s1_rgb <= 24'd0;
        end else begin
            s1_y   <= y_lum;
            s1_d_r <= d_r;
            s1_d_g <= d_g;
            s1_d_b <= d_b;
            s1_c_r <= is_chroma_r;
            s1_c_g <= is_chroma_g;
            s1_c_b <= is_chroma_b;
            s1_rgb <= rgb_in;
        end
    end

    //========================================================================
    //========== 流水级 2（组合部分）：色度放大 + 加回 Y + 限幅 ==========
    //========================================================================
    //   说明：这里两路并行算出结果再二选一，而不是先选增益再乘一次。
    //   目的：让 SAT_GAIN 始终是编译期常量，综合器得以把它优化为移位加。
    //     · 彩色分支：out = Y + (dC × SAT_GAIN) >>> 6
    //     · 灰色分支：out = Y + dC（即增益 1.0x，等价于原样还原）
    //========================================================================

    //---- 2.1 彩色分支：常量乘法 + 算术右移 6 位（还原 6 位小数定点）----
    //     >>> 为算术右移，保留符号位，负数不会错。
    wire signed [19:0] prod_r = s1_d_r * $signed({1'b0, SAT_GAIN});
    wire signed [19:0] prod_g = s1_d_g * $signed({1'b0, SAT_GAIN});
    wire signed [19:0] prod_b = s1_d_b * $signed({1'b0, SAT_GAIN});

    wire signed [19:0] sat_r = prod_r >>> 6;
    wire signed [19:0] sat_g = prod_g >>> 6;
    wire signed [19:0] sat_b = prod_b >>> 6;

    //---- 2.2 灰色分支：增益恒为 1.0x，直接把 dC 符号扩展即可 ----
    wire signed [19:0] d_ext_r = {{10{s1_d_r[9]}}, s1_d_r};
    wire signed [19:0] d_ext_g = {{10{s1_d_g[9]}}, s1_d_g};
    wire signed [19:0] d_ext_b = {{10{s1_d_b[9]}}, s1_d_b};

    //---- 2.3 二选一（由第 1 拍锁存的"是否彩色"标志决定）----
    wire signed [19:0] s_r = s1_c_r ? sat_r : d_ext_r;
    wire signed [19:0] s_g = s1_c_g ? sat_g : d_ext_g;
    wire signed [19:0] s_b = s1_c_b ? sat_b : d_ext_b;

    //---- 2.4 加回亮度 Y（Y 无符号 0~255，符号扩展到 20 位后相加）----
    wire signed [19:0] o_r = $signed({12'd0, s1_y}) + s_r;
    wire signed [19:0] o_g = $signed({12'd0, s1_y}) + s_g;
    wire signed [19:0] o_b = $signed({12'd0, s1_y}) + s_b;

    //---- 2.5 限幅到 0~255 ----
    //     必须做：若不做钳位，增强后溢出会被截断"绕回"（如 300 → 44），
    //     红色区域反而变暗，出现严重色偏。
    wire [7:0] r_out = (o_r > 20'sd255) ? 8'd255 :     // 上限钳位
                       (o_r < 20'sd0  ) ? 8'd0   :     // 下限钳位（负数绕回防护）
                                          o_r[7:0];    // 0~255 内直接取低 8 位
    wire [7:0] g_out = (o_g > 20'sd255) ? 8'd255 :
                       (o_g < 20'sd0  ) ? 8'd0   :
                                          o_g[7:0];
    wire [7:0] b_out = (o_b > 20'sd255) ? 8'd255 :
                       (o_b < 20'sd0  ) ? 8'd0   :
                                          o_b[7:0];

    //========================================================================
    //========== 流水级 2（寄存器）：输出 ==========
    //========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            rgb_out <= 24'd0;
        else if (EN)
            rgb_out <= {r_out, g_out, b_out};   // 饱和度增强
        else
            rgb_out <= s1_rgb;                  // 旁路（延迟同为 2 拍，便于 A/B 对比）
    end

endmodule

//============================================================================
// 使用提示
//----------------------------------------------------------------------------
// · 颜色还不够浓：SAT_GAIN 96 → 112（1.75x）；浓得发假/出色块 → 降到 80
// · 灰色区域出现红绿蓝杂色噪点：DEADZONE 3 → 5 或 6
// · 想确认饱和度到底起了多大作用：把 EN 改成 0 重新编译，拍图对比
// · 本模块相对输入延迟 2 拍，只影响彩色原图模式（表现为右移 1 像素，不可见）
// · 若后续仍出现时序问题，可进一步把第 1 级再拆：把 dC 计算与死区比较分开寄存
// · 若要提高"色准"而不只是"浓度"，应在 AWB 之后加 CCM 颜色校正矩阵，
//   本模块只负责浓度，不修正色相偏差。
//============================================================================
