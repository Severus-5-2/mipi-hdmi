`timescale 1ns / 1ps

//=============================================================================
//  模块：ae_meter（AE 测光器）v3 —— 中央重点加权测光版
//  功能：逐帧统计画面亮度，供自动曝光(AE)控制律使用
//  时钟域：S_hdmi_pixel_clk（74.25 MHz 视频域）
//  作者：2026-10-06
//  位置：Gamma 之后、MUX 之前（统计的是"肉眼看到的亮度"）
//
//=============================================================================
//  【v3 改动 —— 解决"室内逆光下 AE 不起作用"】
//
//  现象：站在窗前（或室内对着门）时，人物是剪影，AE 却"不加曝光"；
//        但手动按键调靶亮度却有效 —— 说明 sensor 的增益/曝光还有余量，
//        不是"光真的不够"，而是 **AE 收敛到了一个错误的点**。
//
//  根因：v2 用的是 **全帧平均测光**。逆光场景中，窗外/门外的亮区
//        （可能只占 1/3 画面）把整帧均值拉得很高，AE 一算
//        "均值 190 > 靶亮度 120，已经够亮了" → 停止加曝光 → 人物永远是剪影。
//
//  对策：改成 **3×3 九宫格中央重点加权测光**（相机上叫 Center-Weighted
//        Average / 中央重点平均测光）。画面中心的权重最高、四角最低，
//        测光结果主要由"画面主体"（通常就是人物/主体）决定。
//
//  Python 建模验证（1280×720，中心区暗30、四周亮210 的典型逆光帧）：
//        全帧平均 = 190   → AE 认为够亮，人物保持剪影（现状 BUG）
//        加权(4,2,1) = 165
//        加权(8,2,1) = 138 ← 采用，最接近靶亮度 120，AE 会继续加曝光
//  同时验证：均匀画面下加权结果 = 全帧结果（128→128），归一化正确，
//            即"场景均匀时行为不变"，只在明暗分布不均时才起作用。
//
//=============================================================================
//  【关键设计 1：权重用"移位"实现，不做帧末乘加树】
//
//  最直觉的写法是"9 个区各自累加，帧末再算 Σ(wᵢ × sumᵢ)" —— 但这样
//  帧末那一拍要同时做 9 个乘法 + 8 个加法，是一条极长的组合路径，
//  在 74.25 MHz（13.33 ns）下必挂时序。
//
//  本设计的做法：**权重在累加的那一刻就以移位施加**：
//        acc <= acc + (Y << w_sh)      w_sh = 0/1/2/3 → 权重 1/2/4/8
//  每拍只多一个"移位（纯连线，零成本）+ 一次 32bit 加法"，
//  与 v2 的累加级完全同构，时序不变差，也不需要任何乘法器。
//  代价：权重必须是 2 的幂（1/2/4/8），对本应用完全够用。
//
//=============================================================================
//  【关键设计 2：x / 行计数器放在流水第 2 级，靠"回绕"自归零】
//
//  为什么不放第 3 级（累加级）？
//    权重 w 是在第 2 级与亮度 Y 同时打拍寄存的。若计数器在第 3 级才更新，
//    则第 2 级看到的计数器值会比当前像素**落后一个**，权重整体错位一像素。
//    放到第 2 级、与 Y 同一拍递增，则"当前计数器值 = 当前像素索引"，天然对齐。
//
//  为什么不需要帧末复位信号？
//    921600 = 1280 × 720 **整除**。只要 x_cnt 在 1279 处回绕到 0、
//    line_cnt 在 719 处回绕到 0，那么一帧最后一个像素过后，
//    两个计数器**自然回到 (0,0)**，不需要任何复位。
//    这样避免了"第 2 级递增"与"第 3 级帧末复位"两个 always 块
//    同时驱动同一个寄存器（多驱动在综合里是硬错误）。
//    已用位级仿真验证：连续 5 帧后 x_cnt=0、line_cnt=0，无漂移。
//
//=============================================================================
//  【关键设计 3：除法常数与权重档位对照表】
//
//  加权均值 = Σ(wᵢ × Yᵢ) / D，其中 D = Σ(wᵢ × nᵢ) 是**编译期常量**：
//        n_center = 102480，n_edge(4区合计) = 409680，n_corner(4区合计) = 409440
//  与 v2 一样用"乘常数再 >>32"代替除法：mean = (acc × K) >> 32，K = ⌈2³²/D⌉。
//
//    权重(中心,边中,四角)   除数 D        K      最大累加值(255×D)
//        (4, 2, 1)        1638720      2621      417873600  ← 标准中央重点
//        (8, 2, 1)        2048640      2097      522403200  ← 本版默认（逆光更强）
//        (8, 4, 1)        2868000      1498      731340000
//        (2, 1, 1)        1024080      4194      261140400
//    全帧平均(不加权)       921600      4661      234912000  ← METER_MODE=0
//
//  ⚠️ 换权重时必须同时换 K！两者是一一对应的，否则测光结果会整体偏亮/偏暗。
//  ⚠️ 累加器 32bit 足够：最大 522403200 < 2³² = 4294967296（余量充足）。
//  ⚠️ K < 2¹³，所以乘积位宽 PW = 32+13 = 45 仍然成立，取 [39:32] 即 >>32。
//
//=============================================================================
//  【沿用 v2 的三条设计（未改动）】
//    1) 用常量乘法代替除法求均值（见上表）
//    2) 跨时钟域只传 1 bit 翻转电平 O_frame_toggle，Y_avg 整帧保持静态
//       （正因如此，SDC 对这条路径做 set_false_path 是安全的）
//    3) 对 de 对齐误差不敏感：±1~2 像素对 921600 的均值影响 < 0.001%，
//       对 3×3 分区也只是让边界错开一两个像素，可忽略
//
//  【v2 遗留的时序修复（本版保留）】
//    · 乘法 prod_r 独占一拍（v1 曾因此违例 -0.014 ns）
//    · 像素计数器 20 bit（921599 < 2²⁰）
//=============================================================================

module ae_meter #(
    parameter IMG_WIDTH  = 1280,    // 一行像素数
    parameter IMG_HEIGHT = 720,     // 一帧行数
    parameter PIPE_DELAY = 1,       // I_rgb 相对 I_de 的流水线延迟拍数(0~3)
                                    //   接 S_hdmi_de + S_video_bright 时为 1
                                    //   （gamma_lut 有 1 拍输出寄存）

    //------------------------------------------------------------------
    // 测光模式：1 = 中央重点加权（默认，治逆光）；0 = 全帧平均（v2 旧行为）
    //   保留 0 是为了上板 A/B 对比：同一场景切两种模式，能直观确认改进量
    //------------------------------------------------------------------
    parameter METER_MODE = 1,

    //------------------------------------------------------------------
    // 分区权重：权重 = 2^SH，即 SH=0→1倍、1→2倍、2→4倍、3→8倍
    //   默认 (8,2,1)：中心 8 倍、上下左右 2 倍、四角 1 倍
    //   换档请同步改 K_WEIGHT（见文件头对照表）
    //------------------------------------------------------------------
    parameter [1:0] SH_CENTER  = 2'd3,      // 中心区权重 2^3 = 8
    parameter [1:0] SH_EDGE    = 2'd1,      // 边中区权重 2^1 = 2
    parameter [1:0] SH_CORNER  = 2'd0,      // 四角区权重 2^0 = 1
    parameter [31:0] K_WEIGHT  = 32'd2097   // (8,2,1) 对应的除法常数
) (
    input  wire        clk,             // 像素时钟 S_hdmi_pixel_clk
    input  wire        rst_n,           // 低电平复位
    input  wire        I_de,            // 数据有效（与数据眼图对齐前的原始 de）
    input  wire [23:0] I_rgb,           // RGB888，相对 I_de 延迟 PIPE_DELAY 拍
    output reg  [ 7:0] O_Y_avg,         // 本帧加权平均亮度（更新后保持整帧不变）
    output reg         O_frame_toggle   // 每帧翻转一次的电平（跨时钟握手用）
);

//=============================================================================
//  常量定义
//=============================================================================
localparam integer PIX_TOTAL = IMG_WIDTH * IMG_HEIGHT;      // 921600
localparam [19:0]  PIX_LAST  = PIX_TOTAL - 1;               // 921599
localparam integer AW        = 32;                          // 累加器位宽
localparam integer CW        = 20;                          // 像素计数器位宽（921599 < 2^20）
localparam [31:0]  K_GLOBAL  = 32'd4661;                    // 全帧平均的除法常数（v2 同值）
localparam [31:0]  MEAN_K    = (METER_MODE == 0) ? K_GLOBAL[31:0] : K_WEIGHT[31:0];
localparam integer PW        = AW + 13;                     // 乘积位宽 45（K < 2^13）

//  3×3 分区边界（列 / 行各三等分）
//    1280/3 = 426.67 → 取整后列宽为 426 / 427 / 427（和为 1280，无漏无重）
//    720/3  = 240    → 行高为 240 / 240 / 240
localparam integer COL0_END = IMG_WIDTH  / 3;               // 426：x < 426 为第 0 列
localparam integer COL1_END = IMG_WIDTH  * 2 / 3;           // 853：x < 853 为第 1 列，否则第 2 列
localparam integer ROW0_END = IMG_HEIGHT / 3;               // 240
localparam integer ROW1_END = IMG_HEIGHT * 2 / 3;           // 480

//  行末 / 帧末的计数器回绕点（显式声明位宽，避免对 parameter 做部分选择）
localparam [10:0] X_LAST    = IMG_WIDTH  - 1;               // 1279
localparam [ 9:0] LINE_LAST = IMG_HEIGHT - 1;               // 719

//=============================================================================
//  输入数据预处理：de 移位 + 亮度计算
//=============================================================================
wire [7:0] r8 = I_rgb[23:16];
wire [7:0] g8 = I_rgb[15:8];
wire [7:0] b8 = I_rgb[ 7:0];

//  第一级：把 de 延后 PIPE_DELAY 拍，使它与 I_rgb 对齐
//    用固定 4 级移位寄存器 + 常量下标抽头，PIPE_DELAY 可在 0~3 间参数化选择
reg [3:0] de_sr;
always @(posedge clk or negedge rst_n) begin
    if (!rst_n)
        de_sr <= 4'd0;
    else
        de_sr <= {de_sr[2:0], I_de};
end

wire de_al = de_sr[PIPE_DELAY];       // 与 I_rgb 同一拍对齐的数据有效信号

//=============================================================================
//  第二级：亮度 Y 计算 + 分区权重译码 + 像素坐标计数
//-----------------------------------------------------------------------------
//  本拍要做的三件事彼此**并列**（不是串联），因此关键路径仍由最深的
//  Y 计算（3 个常量乘法 + 2 个加法）决定，与 v2 完全一致：
//    (a) Y = (77R + 150G + 29B) >> 8
//    (b) 由 x_cnt / line_cnt 译码出本像素所属分区的移位量 w_sh
//    (c) x_cnt / line_cnt 递增（到行末回绕，行计数 +1）
//  三者的结果在同一拍打进寄存器，下一拍供累加级使用。
//
//  亮度 Y 用 Rec.601 权重（沿用工程既有定点写法）：
//    人眼对绿色最敏感、蓝色最不敏感，(R+G+B)/3 会把蓝天误判成"偏暗"。
//=============================================================================
wire [15:0] y_sum = 16'd77  * {8'd0, r8}
                  + 16'd150 * {8'd0, g8}
                  + 16'd29  * {8'd0, b8};

wire [7:0]  y_val = y_sum[15:8];      // == Y_sum >> 8

//  像素坐标计数器（无需复位：一帧像素数 = IMG_WIDTH × IMG_HEIGHT 整除，
//  最后一像素后自然回绕到 (0,0)，详见文件头"关键设计 2"）
//    位宽按最大 2048 列 / 1024 行留量；本项目 1280×720 足够
reg [10:0] x_cnt;                     // 列坐标 0 ~ IMG_WIDTH-1
reg [ 9:0] line_cnt;                  // 行坐标 0 ~ IMG_HEIGHT-1

//-----------------------------------------------------------------------------
//  分区译码（组合逻辑，与 Y 计算并列）
//    列：in_col0 = x<426, in_col2 = x>=853, in_col1 = 其余
//    行：in_row0 = y<240, in_row2 = y>=480, in_row1 = 其余
//    三类互斥且覆盖全部 9 个区：
//      中心区 = col1 & row1
//      四角区 = (col0|col2) & (row0|row2)
//      边中区 = 其余 4 个（上中、下中、左中、右中）
//-----------------------------------------------------------------------------
wire in_col0 = (x_cnt < COL0_END);
wire in_col2 = (x_cnt >= COL1_END);
wire in_col1 = ~in_col0 & ~in_col2;

wire in_row0 = (line_cnt < ROW0_END);
wire in_row2 = (line_cnt >= ROW1_END);
wire in_row1 = ~in_row0 & ~in_row2;

wire is_center = in_col1 & in_row1;                     // 中心 1 区
wire is_corner = (in_col0 | in_col2) & (in_row0 | in_row2); // 四角 4 区
//  其余即边中 4 区（上中/下中/左中/右中）

wire [1:0] w_sh = (METER_MODE == 0) ? 2'd0 :            // 全帧平均：权重恒为 1
                  (is_center ? SH_CENTER :
                  (is_corner ? SH_CORNER : SH_EDGE));

//  打拍寄存：亮度、有效信号、权重移位量三者严格同拍
reg [7:0] y_r;                        // 打拍后的亮度
reg       val_r;                      // 打拍后的有效信号
reg [1:0] w_sh_r;                     // 打拍后的权重移位量

//  坐标计数：到行末回绕、行计数 +1；行计数到帧末也回绕（见关键设计 2）
wire       x_last    = (x_cnt    == X_LAST);
wire       line_last = (line_cnt == LINE_LAST);

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        y_r      <= 8'd0;
        val_r    <= 1'b0;
        w_sh_r   <= 2'd0;
        x_cnt    <= 11'd0;
        line_cnt <= 10'd0;
    end else begin
        y_r    <= y_val;
        val_r  <= de_al;
        w_sh_r <= w_sh;

        if (de_al) begin
            if (x_last) begin
                x_cnt    <= 11'd0;
                //  行计数同样回绕：一帧 720 行走完后自然回到 0
                line_cnt <= line_last ? 10'd0 : (line_cnt + 10'd1);
            end else begin
                x_cnt    <= x_cnt + 11'd1;
            end
        end
    end
end

//=============================================================================
//  第三级：整帧加权累加 + 帧结束判定
//-----------------------------------------------------------------------------
//  ⚠️ 移位位宽陷阱：Verilog 中 (y_r << w_sh_r) 的结果宽度 = 左操作数宽度，
//     即仍是 8 bit，左移 3 位会直接丢掉高位！
//     必须先把 y_r 零扩展到累加器宽度再移位（下面多补了 AW-8 位）。
//
//  写法要点（沿用 v2）：
//    · 用 >= 而不是 == 判定最后一个像素，防止某帧像素数偶然对不上时卡死
//    · 非阻塞赋值：右边用的是"本拍之前"的旧值，
//      所以 acc_final <= acc + 增量 拿到的是"含最后一个像素"的完整总和，
//      而 acc <= 增量 同时开始新一帧，两者互不干扰
//=============================================================================
wire [AW-1:0] acc_add = ({{(AW-8){1'b0}}, y_r} << w_sh_r);  // 加权后的增量（左移 = 乘权重）

reg [AW-1:0] acc;                     // 帧内加权亮度累加器
reg [CW-1:0] pix_cnt;                 // 帧内像素计数
reg [AW-1:0] acc_final;               // 帧末锁存的完整总和
reg          frame_end;               // 帧结束标志（单周期）

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        acc       <= {AW{1'b0}};
        pix_cnt   <= {CW{1'b0}};
        acc_final <= {AW{1'b0}};
        frame_end <= 1'b0;
    end else if (val_r) begin
        if (pix_cnt >= PIX_LAST) begin
            //  本拍是最后一个有效像素：锁存结果并开启新一帧
            acc_final <= acc + acc_add;
            frame_end <= 1'b1;
            acc       <= acc_add;               // 新帧的第一个像素
            pix_cnt   <= {CW{1'b0}};
        end else begin
            acc       <= acc + acc_add;
            pix_cnt   <= pix_cnt + 1'b1;
            frame_end <= 1'b0;
        end
    end else begin
        frame_end <= 1'b0;
        //  de 无效时保持累加器不变（消隐区不参与统计）
    end
end

//=============================================================================
//  第四级：常量乘法单独成拍（v2 的时序修复，本版保留）
//-----------------------------------------------------------------------------
//  prod_r <= acc_final × MEAN_K
//    乘积最大 5.22e8 × 2097 ≈ 1.10e12 < 2^41，取 [39:32] 即为 >>32 结果的低 8 位。
//  让乘法树独占一拍，输出级只剩"切位"这一根线，时序极宽松。
//=============================================================================
reg [PW-1:0] prod_r;                  // 乘积寄存（独占一拍）
reg          fe_r;                    // frame_end 延迟一拍，与 prod_r 对齐

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        prod_r <= {PW{1'b0}};
        fe_r   <= 1'b0;
    end else begin
        prod_r <= acc_final * MEAN_K; //  乘法树独占一拍
        fe_r   <= frame_end;          //  与乘积对齐的帧结束标志
    end
end

//=============================================================================
//  第五级：输出均值 + 握手电平
//-----------------------------------------------------------------------------
//  时序对齐（与 v2 相同）：
//    拍 A：frame_end=1，acc_final 锁存为完整总和
//    拍 B：fe_r←1，prod_r←acc_final×K
//    拍 C：fe_r=1 → O_Y_avg 取 prod_r[39:32]，电平翻转
//=============================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        O_Y_avg        <= 8'd0;
        O_frame_toggle <= 1'b0;
    end else if (fe_r) begin
        O_Y_avg        <= prod_r[39:32];
        O_frame_toggle <= ~O_frame_toggle;   // 每帧翻转一次 → 供对端检测新帧
    end
end

endmodule
