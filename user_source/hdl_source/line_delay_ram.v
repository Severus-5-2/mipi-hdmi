//============================================================================
// 文件    ：line_delay_ram.v
// 功能    ：图像单行延时线（把数据流整体延后一整行 = IMG_WIDTH 个像素）
// 版本    ：v1（2026-10-05）
//============================================================================
//
// 【作用】
//   构建 3×3 卷积窗口时，需要"上一行同列"和"上上行同列"的数据。
//   本模块提供**恰好一行**的延时，两级串联即可得到两行延时。
//
// 【工作原理】
//   地址随像素流循环递增（0 → IMG_WIDTH-1 → 0 ...），写入的同时读取同一地址：
//     · 当前周期写入的是"本行的第 a 列"；
//     · 读出的则是"上一次写该地址的内容"，也就是**上一行的第 a 列**。
//   因此对本模块而言：写当前行、读上一行，延时正好一行，且自动保持列对齐。
//
// 【对 BRAM 推断的要求（重要）】
//   必须综合成 Block RAM，绝不能用 LUT 拼：
//     IMG_WIDTH=1280 × 24bit ≈ 30 Kbit，若推断失败会耗掉数千个 LUT，直接爆资源。
//   这里使用的是业界通用的"同步写 + 输出寄存"单端口 RAM 模板，
//   各主流综合器（含安路 TD 基于的 Synplify）都能可靠推断为 BRAM。
//   若 TA/TD 报告资源异常暴涨，请检查是否被推断成了分布式 RAM。
//
// 【关于读写同一地址】
//   本设计依赖 read-first（先读旧值、再写入新值）语义。
//   这是上述 RAM 模板在综合器中的默认推断结果；
//   如果工具映射到了 write-first 的存储原语，会导致行延时失效（画面出现竖向条纹），
//   此时需要把读写地址错开一拍，请联系作者调整。
//
//============================================================================

module line_delay_ram #(
    parameter        IMG_WIDTH = 1280,   // 一行像素数（必须与视频时序一致）
    parameter        ADDR_W    = 12,     // 地址位宽：2^12 = 4096 > 1280，留余量
    parameter        DW        = 24      // 数据位宽：本工程打包传输 {Y, Cr, Cb}
) (
    input  wire             clk,         // 像素时钟
    input  wire             rst_n,       // 低电平复位（仅复位输出寄存器）
    input  wire             I_wen,       // 写使能：接伴随数据的有效信号（I_de 的同步延时版本）
    input  wire [ADDR_W-1:0] I_addr,     // 读写共用的行内列地址
    input  wire [DW-1:0]    I_data,      // 写入数据（当前行）
    output reg  [DW-1:0]    O_data       // 读出数据（上一行同列，相对输入延时 1 行 + 1 拍）
);

    //------------------------------------------------------------------------
    // 存储本体
    //------------------------------------------------------------------------
    reg [DW-1:0] mem [0:IMG_WIDTH-1];

    //------------------------------------------------------------------------
    // 同步写 + 同步读（输出寄存一拍）
    //   读写地址相同：读出的是写入之前的旧内容，即上一行同列的数据。
    //------------------------------------------------------------------------
    always @(posedge clk) begin
        if (I_wen)
            mem[I_addr] <= I_data;      // 写入当前行
        O_data <= mem[I_addr];          // 读出上一行同列（旧内容）
    end

endmodule
