//============================================================================
// 文件    ：chroma_denoise.v
// 功能    ：色度降噪（Cb/Cr 域低通）—— 消除高增益下的彩色噪点，同时不损失清晰度
// 位置    ：Gamma 校正之后、饱和度增强之前（显示域）
// 版本    ：v3（2026-10-05）
//
// ┌──────────────────────────────────────────────────────────────────────┐
// │ v3 修复记录：满屏蓝黄噪点（色度通道随机饱和）                        │
// │                                                                      │
// │ 现象：亮度恢复正常后，彩色模式满屏蓝/黄/橙色椒盐噪点，但灰度模式      │
// │       正常，且画面明暗结构可见（亮度是对的，坏的只有色度）。          │
// │                                                                      │
// │ 根因：级 5 中 r_div[9:0] 这类**部分选择的结果永远是无符号**，         │
// │       导致含它的加法表达式整体按无符号运算：                          │
// │         负色度分量 -180（低10位补码=844）被零扩展成 +844，            │
// │         R = Y+844 → 限幅255；G 是减法 → Y-844 → 限幅0。               │
// │       色度噪声逐像素随机正负 → 通道随机砸到 0/255 → 饱和椒盐噪点。    │
// │       比特级仿真：色度噪声 σ=6 时 67.2% 像素饱和（修复后 0%）。       │
// │                                                                      │
// │ 修复：去掉 [9:0] 部分选择，直接把完整的 signed 向量相加（见级 5）。   │
// └──────────────────────────────────────────────────────────────────────┘
//
// ┌──────────────────────────────────────────────────────────────────────┐
// │ v2 修复记录（严重 BUG，导致画面几乎全黑）                            │
// │                                                                      │
// │ 现象：接上本模块后，彩色原图模式画面极暗、几乎全黑，用手机闪光灯      │
// │       照射镜头也无反应；而灰度/二值/Sobel 模式完全正常。              │
// │                                                                      │
// │ 根因：级 5（YCbCr → RGB）的定点运算写错了量纲 ——                     │
// │       错误地把「Y + 系数×色差」这个**整体**一起除以了 256，          │
// │       导致亮度 Y 也被除掉。中性灰 Y=128 时输出 R=G=B=1。             │
// │       由于本模块只串在彩色通路上，灰度分支不受影响，                  │
// │       于是出现了"彩色全黑、灰度正常"这个极具迷惑性的现象。            │
// │                                                                      │
// │ 修复：只对「系数 × 色差」的乘积除以 256，Y 单独相加（详见级 5 注释）。│
// │                                                                      │
// │ 验证：RGB→YCbCr→RGB 往返误差 平均 126.91 → 0.78；                    │
// │       256 级灰阶不一致数 255 → 0；亮度守恒偏差 0。                   │
// │                                                                      │
// │ 排查思路备忘：灰度正常而彩色异常 ⇒ 问题必然出在"只有彩色通路才       │
// │       经过"的模块上。本例中该模块就是 chroma_denoise + sat_enhance。  │
// └──────────────────────────────────────────────────────────────────────┘
//============================================================================
//
// 【为什么只降噪色度而不降噪亮度】
//   仔细观察 HDMI 画面会发现：噪点是**花花绿绿的彩色雪花**，而物体的轮廓、
//   边缘、纹理其实还算清楚。原因是对颜色的感知和对亮度的感知机制不同：
//     · 亮度（Y）携带了绝大部分图像细节，一动就糊 —— 所以**亮度一根毛都不动**；
//     · 色度（Cb/Cr）人眼分辨率低（约亮度的 1/4），做低通几乎看不出损失，
//       但**彩色噪点正存在于此**，平滑掉收益极大。
//   这就是专业 ISP 里"色度降噪（Chroma NR）"独立于"亮度降噪"存在的原因。
//   本模块只动色度，因此在消噪点的同时**不会产生"糊脸"效果**。
//
// 【算法】
//   RGB → YCbCr → Cb/Cr 做 3×3 可分离加权低通 → RGB
//     3×3 高斯核（可分离形式）：[1 2 1] × [1 2 1] / 16
//   亮度 Y 完全旁路，只在流水线里做等量的延时以保持不变对齐。
//
// 【流水线结构（严格两级以内逻辑，避免重蹈 sat_enhance v1 的时序违例）】
//   级 1：RGB → Y/Cb/Cr                      （寄存）
//   级 2：水平抽头延时 + [1 2 1]/4 水平低通   （寄存）
//   级 3：行延时 RAM ×2（得到上 1 行、上 2 行）（BRAM 输出自带寄存）
//   级 4：[1 2 1]/4 垂直低通                 （组合，浅）
//   级 5：YCbCr → RGB + 限幅                 （寄存）
//   每一级之间都有寄存器，单级逻辑 ≤4 级，74.25 MHz 下时序宽松。
//
// 【延时与几何位移】
//   窗口中心滞后：**垂直 1 行 + 水平 1 像素**。
//   表现为彩色原图模式画面上移 1 行、右移 1 像素 —— 人眼不可察觉，
//   且本模块只接在彩色通路，灰度/二值/Sobel 完全不受影响。
//
// 【资源】
//   2 个行延时 RAM（1280 × 24bit）≈ 3~4 个 18Kb BRAM，外加少量逻辑，无乘法器。
//
// 【NR_MODE 参数（A/B 对比用，编译期选择）】
//     0 = 完全旁路（直通）
//     1 = 仅做水平 1×3 低通（**不消耗 BRAM**，效果约为完整版的 60%）
//     2 = 完整 3×3 低通（默认，效果最好）
//   上板若怀疑行延时 RAM 有问题（画面出现周期性竖条纹），可先切到 1 验证。
//
//============================================================================

module chroma_denoise #(
    parameter        IMG_WIDTH = 1280,   // 一行像素数，必须与视频时序一致
    parameter        ADDR_W    = 12,     // 列地址位宽
    parameter [1:0]  NR_MODE   = 2'd2,   // 0:旁路  1:仅水平  2:完整3×3
    parameter        NR_EN     = 1'b1    // 总开关：1 启用；0 直通
) (
    input  wire             clk,         // 像素时钟（S_hdmi_pixel_clk）
    input  wire             rst_n,       // 低电平复位
    input  wire             I_de,        // 数据有效（必须与 rgb_in 同一拍对齐）
    input  wire [23:0]      rgb_in,      // 输入 RGB888
    output reg  [23:0]      rgb_out      // 输出 RGB888
);

    //========================================================================
    // 级 1 组合：RGB → YCbCr（Rec.601 定点化，系数和均为 256，右移 8 位）
    //========================================================================
    wire [7:0] r_in = rgb_in[23:16];
    wire [7:0] g_in = rgb_in[15:8];
    wire [7:0] b_in = rgb_in[7:0];

    // 把无符号通道值扩展为 18bit 有符号（符号位为 0），便于统一做有符号运算
    wire signed [17:0] r_ext = $signed({10'd0, r_in});
    wire signed [17:0] g_ext = $signed({10'd0, g_in});
    wire signed [17:0] b_ext = $signed({10'd0, b_in});

    // Y  =  0.299R + 0.587G + 0.114B                 → 77/256, 150/256,  29/256
    // Cb = -0.169R - 0.331G + 0.500B + 128           → -43/256, -85/256, 128/256
    // Cr =  0.500R - 0.419G - 0.081B + 128           → 128/256, -107/256, -21/256
    // 常数乘法由综合器自动优化为移位加网络，不消耗 DSP。
    // 18bit 有符号量纲 ±131071，而本式值域最大 65280，不会溢出。
    wire signed [17:0] y_calc  =  18'sd77  * r_ext +  18'sd150 * g_ext +  18'sd29 * b_ext;
    wire signed [17:0] cb_calc = -18'sd43  * r_ext + -18'sd85  * g_ext +  18'sd128 * b_ext;
    wire signed [17:0] cr_calc =  18'sd128 * r_ext + -18'sd107 * g_ext + -18'sd21  * b_ext;

    // 右移 8 位完成除法。这里加了 +128 做**四舍五入**：
    //   若直接截断，每次都会向负无穷方向偏 1 LSB，多次累积会让整体略偏暗、
    //   并带来 ±2~4 的往返误差；四舍五入后误差减半且正负对称。
    wire signed [9:0] y_pre  = (y_calc  + 18'sd128) >>> 8;
    wire signed [9:0] cb_pre = ((cb_calc + 18'sd128) >>> 8) + 10'sd128;
    wire signed [9:0] cr_pre = ((cr_calc + 18'sd128) >>> 8) + 10'sd128;

    // 限幅到 0~255（防止计算过程超出色域）
    wire [7:0] y_w  = (y_pre  > 10'sd255) ? 8'd255 : (y_pre  < 0) ? 8'd0 : y_pre [7:0];
    wire [7:0] cb_w = (cb_pre > 10'sd255) ? 8'd255 : (cb_pre < 0) ? 8'd0 : cb_pre[7:0];
    wire [7:0] cr_w = (cr_pre > 10'sd255) ? 8'd255 : (cr_pre < 0) ? 8'd0 : cr_pre[7:0];

    //========================================================================
    // 级 1 寄存器
    //========================================================================
    reg        s1_de;
    reg [7:0]  s1_y, s1_cb, s1_cr;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s1_de <= 1'b0;
            s1_y  <= 8'd0;  s1_cb <= 8'd128;  s1_cr <= 8'd128;
        end else begin
            s1_de <= I_de;
            s1_y  <= y_w;
            s1_cb <= cb_w;
            s1_cr <= cr_w;
        end
    end

    //------------------------------------------------------------------------
    // 列地址计数器：与级 1 输出对齐（用 s1_de 使能）
    //   每行从 0 递增到 IMG_WIDTH-1，行间（de 为低）自动清零，保证行对齐。
    //------------------------------------------------------------------------
    reg [ADDR_W-1:0] col_cnt;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            col_cnt <= {ADDR_W{1'b0}};
        else if (s1_de)
            col_cnt <= (col_cnt == IMG_WIDTH[ADDR_W-1:0] - 1'b1) ? {ADDR_W{1'b0}} : col_cnt + 1'b1;
        else
            col_cnt <= {ADDR_W{1'b0}};
    end

    //========================================================================
    // 级 2 组合：水平三抽头 + [1 2 1]/4 低通
    //========================================================================
    reg [7:0] y_t1,  y_t2;      // t1 = 当前像素前 1 列，t2 = 前 2 列
    reg [7:0] cb_t1, cb_t2;
    reg [7:0] cr_t1, cr_t2;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            y_t1  <= 8'd0;   y_t2  <= 8'd0;
            cb_t1 <= 8'd128; cb_t2 <= 8'd128;
            cr_t1 <= 8'd128; cr_t2 <= 8'd128;
        end else begin
            y_t1  <= s1_y;  y_t2  <= y_t1;      // 亮度：只做延时，不做平滑
            cb_t1 <= s1_cb; cb_t2 <= cb_t1;
            cr_t1 <= s1_cr; cr_t2 <= cr_t1;
        end
    end

    // 以 t1（前一列）为窗口中心：[t2, t1, s1] = [n-2, n-1, n]
    // 三个 8bit 之和最大 4×255 = 1020，10bit 足够。
    // ⚠️ **只对色度求和**：亮度 Y 不参与任何平滑，这是本模块的核心原则。
    wire [9:0] h_cb_sum = cb_t2 + (cb_t1 << 1) + s1_cb;
    wire [9:0] h_cr_sum = cr_t2 + (cr_t1 << 1) + s1_cr;

    //========================================================================
    // 级 2 寄存器：打包成 24bit 总线 {Y, Cr, Cb} 供后续行延时使用
    //   亮度 Y 只取中层抽头 y_t1 —— **原样通过、仅承担 1 像素延时**，
    //   用于与色度保持对齐，绝不参与平滑。
    //   同时把 de 与列地址打拍，使之与打包数据严格同步 —— 这是行延时 RAM
    //   能自动保持列对齐的关键。
    //========================================================================
    reg        h_de;
    reg [ADDR_W-1:0] h_addr;
    reg [7:0]  hr_y, hr_cb, hr_cr;      // hr_* = horizontal result（已寄存）

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            h_de   <= 1'b0;
            h_addr <= {ADDR_W{1'b0}};
            hr_y   <= 8'd0;  hr_cb <= 8'd128;  hr_cr <= 8'd128;
        end else begin
            h_de   <= s1_de;
            h_addr <= col_cnt;
            hr_y   <= y_t1;              // 亮度：延时对齐，不滤波
            hr_cb  <= h_cb_sum[9:2];     // 色度：除以 4 完成 [1 2 1] 归一化
            hr_cr  <= h_cr_sum[9:2];
        end
    end

    // h_bus 组合打包（24bit）
    wire [23:0] h_bus = {hr_y, hr_cr, hr_cb};

    //========================================================================
    // 级 3：两级行延时 RAM，得到"上一行"与"上上行"的同列数据
    //========================================================================
    wire [23:0] p1_bus;     // 上一行（中心行）
    wire [23:0] p2_bus;     // 上上行

    line_delay_ram #(
        .IMG_WIDTH (IMG_WIDTH),
        .ADDR_W    (ADDR_W   ),
        .DW        (24       )
    ) u_line1 (
        .clk    (clk   ),
        .rst_n  (rst_n ),
        .I_wen  (h_de  ),     // 写使能：当前行有效
        .I_addr (h_addr),     // 读写共用列地址
        .I_data (h_bus ),     // 写入当前行的水平滤波结果
        .O_data (p1_bus)      // 读出上一行同列（延时 1 行 + 1 拍）
    );

    // p1 相对 h_bus 晚 1 行 + 1 拍，因此其 de 与地址也要同步延后 1 拍
    reg        p1_de;
    reg [ADDR_W-1:0] p1_addr;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            p1_de   <= 1'b0;
            p1_addr <= {ADDR_W{1'b0}};
        end else begin
            p1_de   <= h_de;
            p1_addr <= h_addr;
        end
    end

    line_delay_ram #(
        .IMG_WIDTH (IMG_WIDTH),
        .ADDR_W    (ADDR_W   ),
        .DW        (24       )
    ) u_line2 (
        .clk    (clk    ),
        .rst_n  (rst_n  ),
        .I_wen  (p1_de  ),
        .I_addr (p1_addr),
        .I_data (p1_bus ),
        .O_data (p2_bus )
    );

    //------------------------------------------------------------------------
    // 对齐：把"当前行"的数据再打一拍，使其与 p1（上一行）、p2（上上行）
    // 在同一时刻给出同一列的三个行抽头。
    //   此时：h_d1 = 当前行 / p1 = 上一行（中心） / p2 = 上上行
    //------------------------------------------------------------------------
    reg [7:0] cur_y, cur_cb, cur_cr;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cur_y <= 8'd0; cur_cb <= 8'd128; cur_cr <= 8'd128;
        end else begin
            cur_y <= hr_y; cur_cb <= hr_cb; cur_cr <= hr_cr;
        end
    end

    wire [7:0] p1_y  = p1_bus[23:16];   // 中心行的亮度（Y 不滤波）
    wire [7:0] p1_cb = p1_bus[ 7:0 ];
    wire [7:0] p1_cr = p1_bus[15:8 ];
    wire [7:0] p2_cb = p2_bus[ 7:0 ];
    wire [7:0] p2_cr = p2_bus[15:8 ];

    //========================================================================
    // 级 4 组合：垂直 [1 2 1]/4 低通（仅作用于色度）
    //   窗口中心为 p1（上一行），故输出整体上移一行。
    //========================================================================
    reg [7:0] v_y, v_cb, v_cr;      // NR_MODE 决定来源，故用 reg 在 generate 之外声明

    generate
        if (NR_MODE == 2'd2) begin : gen_nr_full
            // 完整 3×3：先水平再垂直（均已各自归一化）
            wire [9:0] v_cb_w = p2_cb + (p1_cb << 1) + cur_cb;
            wire [9:0] v_cr_w = p2_cr + (p1_cr << 1) + cur_cr;
            always @(*) begin
                v_y  = p1_y;        // 亮度取中心行，不滤波
                v_cb = v_cb_w[9:2]; // 除以 4
                v_cr = v_cr_w[9:2];
            end
        end else if (NR_MODE == 2'd1) begin : gen_nr_h_only
            // 仅水平低通：不使用行延时 RAM（零 BRAM 占用）
            always @(*) begin
                v_y  = cur_y;
                v_cb = cur_cb;
                v_cr = cur_cr;
            end
        end else begin : gen_nr_bypass
            // 旁路：数据原样通过（仅承担流水线延时）
            always @(*) begin
                v_y  = cur_y;
                v_cb = cur_cb;
                v_cr = cur_cr;
            end
        end
    endgenerate

    //========================================================================
    // 级 5 组合：YCbCr → RGB
    //     R = Y + 1.402·(Cr-128)                  → 359/256
    //     G = Y - 0.344·(Cb-128) - 0.714·(Cr-128) → 88/256, 183/256
    //     B = Y + 1.772·(Cb-128)                  → 454/256
    //
    //  ⚠️⚠️⚠️【v2 修复的致命 BUG —— 请务必理解，定点运算中极易重犯】⚠️⚠️⚠️
    //
    //  v1 的错误写法：
    //      r_calc = Y + (359 * cr_d);            // 先把 Y 和乘积加在一起
    //      r_s    = (r_calc + 128) >>> 8;        // 再对「整个和式」除以 256
    //
    //  错在哪：除以 256 是为了把「系数 × 色差」还原成 0~255 量纲，
    //          **这个除法只能作用于乘积项，绝不能作用于 Y**。
    //          v1 却把 Y 也一起除了 256，亮度直接被抹掉：
    //            中性灰 Y=128、Cr=128(色差=0) 时 → (128+0+128)>>>8 = 1
    //            输出 R=G=B=1，画面几乎全黑 —— 这正是 v1 上板的实测现象。
    //
    //  正确写法：**只对色度乘积除以 256，再与 Y 相加**：
    //      R = Y + ((359 * cr_d + 128) >>> 8)
    //  这样 Y 的量纲（0~255）原封不动，色度分量才是正确的加权值。
    //========================================================================
    wire signed [9:0] cr_d = $signed({2'b00, v_cr}) - 10'sd128;
    wire signed [9:0] cb_d = $signed({2'b00, v_cb}) - 10'sd128;

    // 第一步：只算「系数 × 色差」的乘积（量纲仍是放大 256 倍的，尚未还原）
    wire signed [17:0] r_mul =  $signed({1'b0, 10'd359}) * cr_d;
    wire signed [17:0] g_mul =  $signed({1'b0, 10'd88 }) * cb_d + $signed({1'b0, 10'd183}) * cr_d;
    wire signed [17:0] b_mul =  $signed({1'b0, 10'd454}) * cb_d;

    // 第二步：只对乘积除以 256（+128 做四舍五入）
    //   值域估算：359×(+127)/256 ≈ +178，359×(-128)/256 ≈ -180，
    //   因此 10bit 有符号（±512）完全够用，截取低 10 位即是正确的补码。
    wire signed [17:0] r_div = (r_mul + 18'sd128) >>> 8;
    wire signed [17:0] g_div = (g_mul + 18'sd128) >>> 8;
    wire signed [17:0] b_div = (b_mul + 18'sd128) >>> 8;

    // 第三步：亮度 Y 与色度分量相加。**Y 不再参与任何除法**。
    //
    //  ⚠️⚠️⚠️【v3 修复的第二个 BUG —— Verilog 的"部分选择必为无符号"陷阱】⚠️⚠️⚠️
    //
    //  v2 的错误写法：
    //      wire signed [10:0] r_pre = $signed({1'b0, v_y}) + r_div[9:0];
    //                                                    ^^^^^^^^^^
    //  错在哪：**Verilog 中对向量的部分选择（bit-select / part-select）的结果
    //          永远是无符号数**，哪怕母向量声明为 signed！
    //          r_div 是 signed [17:0]，但 r_div[9:0] 是 unsigned [9:0]。
    //          加法表达式里只要有一个无符号操作数，**整个表达式按无符号运算**：
    //            · 负的色度分量（如 -180，低10位补码 = 844）被零扩展成 +844；
    //            · R = Y + 844 → 限幅 255（B 通道同理 → 蓝/黄噪点）；
    //            · G 是减法：Y - 844 → 限幅 0。
    //          色度噪声逐像素随机正负 → 通道随机砸到 0/255 → 满屏饱和蓝黄噪点，
    //          而亮度 Y 不经过这些加法 → 灰度结构完好 —— v2 上板实测现象。
    //
    //  正确写法：**直接把完整的 signed 向量相加**，让表达式保持有符号属性。
    //          r_div 虽是 18bit，但其值域已验证在 ±512 内，直接相加不会溢出：
    //            19bit 和 = 9bit(Y≤255) + 18bit(±512)，最大 |值| ≈ 767，安全。
    wire signed [18:0] r_pre = $signed({1'b0, v_y}) + r_div;
    wire signed [18:0] g_pre = $signed({1'b0, v_y}) - g_div;
    wire signed [18:0] b_pre = $signed({1'b0, v_y}) + b_div;

    // 限幅到 0~255：色彩空间转换越界非常常见，不钳位会出现严重色斑
    //   注意比较阈值位宽要与 r_pre 一致（19bit），混合位宽比较有符号数会出错
    wire [7:0] r_out = (r_pre > 19'sd255) ? 8'd255 : (r_pre < 0) ? 8'd0 : r_pre[7:0];
    wire [7:0] g_out = (g_pre > 19'sd255) ? 8'd255 : (g_pre < 0) ? 8'd0 : g_pre[7:0];
    wire [7:0] b_out = (b_pre > 19'sd255) ? 8'd255 : (b_pre < 0) ? 8'd0 : b_pre[7:0];

    //========================================================================
    // 级 5 寄存器：输出
    //========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            rgb_out <= 24'd0;
        else if (NR_EN)
            rgb_out <= {r_out, g_out, b_out};
        else
            rgb_out <= rgb_in;          // 总开关关闭时直通（A/B 对比用）
    end

endmodule

